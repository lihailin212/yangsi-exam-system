def norm(s):
    s = re.sub(r"<[^>]+>", "", s or "")
    return re.sub(r"[\s　]+", "", s)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--apply-all", action="store_true", help="不限制命中数（默认只给唯一命中的写）")
    args = ap.parse_args()

    conn = connect()
    cur = conn.cursor()
    cur.execute("select id, content, category from questions")
    rows = [(qid, norm(c), cat) for qid, c, cat in cur.fetchall()]

    used = set()
    hit = 0
    for key, mnemonic in MNEMONICS:
        k = norm(key)
        if k in used:
            print(f"  ! 片段重复，跳过：{key}")
            continue
        used.add(k)
        matched = [(qid, cat) for qid, text, cat in rows
                   if k in text and not any(sk in (cat or "") for sk in SKIP_CATEGORY)]
        if not matched:
            print(f"  · 没匹配到：{key}")
            continue
        if len(matched) > 1 and not args.apply_all:
            print(f"  ! 命中 {len(matched)} 道，先不写：{key} -> {[m[0] for m in matched]}")
            continue
        for qid, cat in matched:
            cur.execute("update questions set mnemonic=%s where id=%s", (mnemonic, qid))
            hit += 1
            print(f"  ✓ id={qid} [{cat}] {key[:22]} → {mnemonic[:22]}…")
    if args.dry_run:
        conn.rollback()
        print(f"（--dry-run，未写库；命中 {hit} 题）")
    else:
        conn.commit()
        print(f"已写入 {hit} 题的巧记")
    conn.close()


if __name__ == "__main__":
    main()
